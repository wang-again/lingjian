import test from 'node:test';
import assert from 'node:assert/strict';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {mkdtemp,readFile,rm} from 'node:fs/promises';
import { integrationMissing } from './fixtures/office-runtime.mjs';
import {tmpdir} from 'node:os';
import {join,resolve,dirname,basename} from 'node:path';
import {OfficeService} from '../lib/office.mjs';
const python=process.env.OFFICE_PYTHON||resolve('.venv-office',process.platform==='win32'?'Scripts/python.exe':'bin/python');
test('本地 OCR 实际识别图片与混合 PDF，导入正文、页码范围和原件保护', {skip: integrationMissing,timeout:90000},async t=>{
 const directory=await mkdtemp(join(tmpdir(),'lingjian-ocr-')),office=new OfficeService(directory,{python});
 t.after(async()=>{office.close();assert.equal(dirname(resolve(directory)),resolve(tmpdir()));assert.ok(basename(directory).startsWith('lingjian-ocr-'));await rm(directory,{recursive:true,force:true,maxRetries:10,retryDelay:100});});
 await promisify(execFile)(python,[resolve('tests/fixtures/ocr_samples.py'),join(directory,'samples')],{windowsHide:true});
 const imageBytes=await readFile(join(directory,'samples/scan.png'));
 const file=await office.upload('扫描.png',imageBytes.toString('base64'));
 const result=await office.call('ocr_document',{file_path:file.id});
 assert.match(result.data.text,/OCR\s*12345/);assert.ok(result.data.pages[0].lines.every(line=>line.confidence>=0 && line.confidence<=1));
 if(process.platform==='win32')assert.match(result.data.text,/文档/);
 assert.ok((await office.extract(file.id)).text.includes('12345'));
 assert.deepEqual(await readFile(await office.safePath(file.id)),imageBytes);
 const pdfBytes=await readFile(join(directory,'samples/mixed.pdf'));
 const pdf=await office.upload('混合.pdf',pdfBytes.toString('base64'));
 const mixed=(await office.call('ocr_document',{file_path:pdf.id})).data;
 assert.equal(mixed.pages[0].source,'ocr'); assert.equal(mixed.pages[1].source,'native');
 assert.match(mixed.pages[0].text,/12345/);assert.match(mixed.pages[1].text,/67890/);
 const extract=await office.extract(pdf.id);assert.match(extract.text,/12345/);assert.match(extract.text,/67890/);assert.ok(extract.warnings.length);
 const forced=await office.call('ocr_document',{file_path:pdf.id,page_range:'1',force_ocr:true});assert.equal(forced.data.pages.length,1);
 await assert.rejects(office.call('ocr_document',{file_path:pdf.id,page_range:'0'}),/范围/);
 await assert.rejects(office.call('ocr_document',{file_path:pdf.id,dpi:1000}),/dpi/);
 await assert.rejects(office.call('ocr_document',{file_path:'../../escape.pdf'}),/文件库/);
 assert.deepEqual(await readFile(await office.safePath(pdf.id)),pdfBytes);
});
